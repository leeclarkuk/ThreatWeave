import type { Model, Threat, Mitigation } from './model.js';
import { labelOf } from './ops.js';
import { PRODUCT_NAME } from './model.js';

export const LEVEL_LABEL = { unknown: 'not assessed', low: 'low', medium: 'medium', high: 'high' } as const;

/** Mitigation status as it should be read: a "verified" claim with stale evidence is not shown as verified. */
export function effectiveMitigationStatus(model: Model, m: Mitigation): string {
  if (m.status !== 'verified') return m.status;
  const stale = m.verification.evidenceIds.some((id) => model.evidence.find((e) => e.id === id)?.stale);
  return stale ? 'verified (evidence stale: re-verify)' : 'verified';
}

/**
 * Readable threat statement. Preconditions may be fragments or sentences, so they are introduced
 * as conditions rather than spliced into the grammar.
 */
export function grammar(source: string, preconditions: string[], action: string, consequence: string, targets = ''): string {
  const cond = preconditions.length ? `, provided that ${preconditions.join(' and ')},` : '';
  return `${source ? `A ${source}` : 'An unspecified actor'}${cond} can ${action || '(action not stated)'}, which leads to ${consequence || '(consequence not stated)'}${targets ? `, affecting ${targets}` : ''}.`;
}

export function threatStatement(model: Model, t: Threat): string {
  return grammar(t.source, t.preconditions, t.action, t.consequence, t.targets.map((r) => labelOf(model, r)).join(', '));
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const BASIS: Record<string, string> = { observed: 'observed', inferred: 'inferred', hypothesis: 'hypothesis (unvalidated)' };

export function renderMarkdownReport(model: Model, opts: { generatedAt?: string } = {}): string {
  const L: string[] = [];
  const open = model.reviewItems.filter((r) => r.status === 'open');
  L.push(`# Threat model: ${model.name}`, '');
  if (model.example) L.push('> **Demonstration model.** This is example content, not an analysis of any real system.', '');
  L.push(`Generated by ${PRODUCT_NAME}${opts.generatedAt ? ` on ${opts.generatedAt}` : ''}. Model id \`${model.id}\`, schema version ${model.schemaVersion}.`, '');
  if (model.description) L.push(model.description, '');
  L.push('## Summary', '');
  L.push('| Item | Count |', '|---|---|');
  const cnt: Array<[string, number]> = [
    ['Components', model.elements.length], ['Data flows', model.flows.length], ['Trust boundaries', model.boundaries.length], ['Assets', model.assets.length],
    ['Threats', model.threats.length], ['Mitigations', model.mitigations.length], ['Assumptions and questions', model.assumptions.length],
    ['Open review items', open.length], ['Pending proposals', model.proposals.filter((p) => p.status === 'pending').length],
    ['Stale evidence', model.evidence.filter((e) => e.stale).length],
  ];
  for (const [k, v] of cnt) L.push(`| ${k} | ${v} |`);
  L.push('');
  L.push('Threats are hypotheses about what could go wrong, not confirmed vulnerabilities. Likelihood and impact are stated judgements with reasons, not scores. Evidence strength is reported separately from severity.', '');

  if (open.length) {
    L.push('## Needs review', '');
    for (const r of open) {
      L.push(`- **${r.target.type} "${esc(labelOf(model, r.target))}"**: ${r.reason}`);
      if (r.trace.length) L.push(`  - Why: ${r.trace.join(' → ')}`);
    }
    L.push('');
  }

  L.push('## Architecture', '');
  if (model.elements.length) {
    L.push('| Component | Kind | Exposure | Technology | Basis |', '|---|---|---|---|---|');
    for (const e of model.elements) L.push(`| ${esc(e.name)} | ${e.kind} | ${e.exposure} | ${esc(e.technology)} | ${BASIS[e.basis]} |`);
    L.push('');
  } else L.push('_No components recorded._', '');
  if (model.flows.length) {
    L.push('### Data flows', '', '| Flow | Protocol | Authenticated | Encrypted | Basis |', '|---|---|---|---|---|');
    for (const f of model.flows) L.push(`| ${esc(labelOf(model, { type: 'flow', id: f.id }))} | ${esc(f.protocol)} | ${f.authenticated} | ${f.encrypted} | ${BASIS[f.basis]} |`);
    L.push('');
  }
  if (model.boundaries.length) {
    L.push('### Trust boundaries', '');
    for (const b of model.boundaries) L.push(`- **${esc(b.name)}** (${b.kind}, trust ${b.trust}): ${b.memberIds.map((m) => labelOf(model, { type: 'element', id: m })).join(', ') || 'no members'}`);
    L.push('');
  }
  if (model.assets.length) {
    L.push('### Assets', '');
    for (const a of model.assets) L.push(`- **${esc(a.name)}** (${a.classification})${a.description ? `: ${esc(a.description)}` : ''}`);
    L.push('');
  }

  L.push('## Assumptions and open questions', '');
  if (model.assumptions.length) {
    for (const a of model.assumptions) L.push(`- [${a.kind}, ${a.status}] ${a.text}${a.answer ? ` Answer: ${a.answer}` : ''}${a.relatesTo.length ? ` (relates to ${a.relatesTo.map((r) => labelOf(model, r)).join(', ')})` : ''}`);
  } else L.push('_None recorded._');
  L.push('');

  L.push('## Threats', '');
  if (!model.threats.length) L.push('_No threats recorded._', '');
  for (const t of model.threats) {
    L.push(`### ${t.title}`, '');
    L.push(`- **Statement:** ${threatStatement(model, t)}`);
    L.push(`- **Status:** ${t.status}. **Basis:** ${BASIS[t.basis]}.${t.stride.length ? ` **STRIDE:** ${t.stride.join('')}.` : ''}`);
    L.push(`- **Likelihood:** ${LEVEL_LABEL[t.likelihood.level]}${t.likelihood.rationale ? `, because ${t.likelihood.rationale}` : ''}`);
    L.push(`- **Impact:** ${LEVEL_LABEL[t.impact.level]}${t.impact.rationale ? `, because ${t.impact.rationale}` : ''}`);
    L.push(`- **Evidence strength:** ${t.evidenceStrength}${t.evidenceRationale ? ` (${esc(t.evidenceRationale)})` : ''}`);
    const ms = model.mitigations.filter((m) => m.threatIds.includes(t.id));
    L.push(`- **Mitigations:** ${ms.length ? ms.map((m) => `${m.title} [${effectiveMitigationStatus(model, m)}]`).join('; ') : 'none linked'}`);
    for (const r of model.reviewItems.filter((x) => x.status === 'open' && x.target.type === 'threat' && x.target.id === t.id)) L.push(`- **Needs review:** ${r.reason}`);
    if (t.provenance.origin !== 'human') L.push(`- **Origin:** ${t.provenance.origin}${t.provenance.actor ? ` (${t.provenance.actor})` : ''}`);
    L.push('');
  }

  L.push('## Mitigations', '');
  if (model.mitigations.length) {
    L.push('| Mitigation | Status | Set by | Threats | Verification evidence |', '|---|---|---|---|---|');
    for (const m of model.mitigations)
      L.push(`| ${esc(m.title)} | ${effectiveMitigationStatus(model, m)} | ${m.statusSetBy ? `${m.statusSetBy.actor} (${m.statusSetBy.actorKind})` : '-'} | ${m.threatIds.map((t) => esc(labelOf(model, { type: 'threat', id: t }))).join('; ') || '-'} | ${m.verification.evidenceIds.length || 'none'} |`);
  } else L.push('_None recorded._');
  L.push('');

  L.push('## Evidence', '');
  if (model.evidence.length) {
    for (const e of model.evidence) L.push(`- ${e.stale ? '**[STALE]** ' : ''}${esc(e.summary)}${e.path ? ` — \`${e.path}${e.lineStart ? `:${e.lineStart}` : ''}\`` : ''}${e.revision ? ` @ ${e.revision.slice(0, 12)}` : ''}${e.stale && e.staleReason ? ` (${e.staleReason})` : ''}`);
  } else L.push('_No evidence recorded._');
  L.push('');

  const recent = model.decisions.slice(-15);
  if (recent.length) {
    L.push('## Recent decisions', '');
    for (const d of recent) L.push(`- ${d.at} ${d.actor}: ${d.action} ${d.subject.type} ${d.subject.id}${d.rationale ? ` — ${esc(d.rationale)}` : ''}`);
    L.push('');
  }
  return L.join('\n');
}
